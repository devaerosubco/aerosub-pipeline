// Slices SOLUTIONS, STAGES, PRIORITIES and seedData() verbatim out of src/main.js
// (the frozen prototype logic) and emits scripts/seed-source.generated.mjs with
// `export`s, so the seed generator runs the *exact* prototype data with zero
// transcription risk. Re-run whenever src/main.js's seed changes.
//   node scripts/gen-seed-source.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const src = readFileSync(join(ROOT, 'src', 'main.js'), 'utf8');

// Extract a top-level declaration. `startMarker` MUST end with the opening
// bracket of the body ("[" or "{"). Balances () [] {} — ignoring brackets inside
// strings / template literals / comments — from that bracket until depth 0, then
// consumes a trailing ';' if present.
function extract(startMarker) {
  const start = src.indexOf(startMarker);
  if (start < 0) throw new Error(`marker not found: ${startMarker}`);
  let i = start + startMarker.length - 1; // sit on the opening bracket
  let depth = 0;
  let str = null; // "'" | '"' | '`'
  let inLineComment = false;
  let inBlockComment = false;
  for (; i < src.length; i++) {
    const c = src[i], p = src[i - 1], n = src[i + 1];
    if (inLineComment) { if (c === '\n') inLineComment = false; continue; }
    if (inBlockComment) { if (c === '*' && n === '/') { inBlockComment = false; i++; } continue; }
    if (str) {
      if (c === '\\') { i++; continue; }
      if (c === str) str = null;
      continue;
    }
    if (c === '/' && n === '/') { inLineComment = true; i++; continue; }
    if (c === '/' && n === '*') { inBlockComment = true; i++; continue; }
    if (c === "'" || c === '"' || c === '`') { str = c; continue; }
    if (c === '(' || c === '[' || c === '{') depth++;
    else if (c === ')' || c === ']' || c === '}') {
      depth--;
      if (depth === 0) {
        let end = i + 1;
        if (src[end] === ';') end++;
        return src.slice(start, end);
      }
    }
  }
  throw new Error(`unbalanced from ${startMarker}`);
}

const solutions = extract('const SOLUTIONS = [');
const stages = extract('const STAGES = [');
const priorities = extract("const PRIORITIES = [");
const seedData = extract('function seedData(){');

const out = `// GENERATED by scripts/gen-seed-source.mjs from src/main.js — do not edit.
/* eslint-disable */
export ${solutions}
export ${stages}
export ${priorities}
export ${seedData}
`;

const target = join(ROOT, 'scripts', 'seed-source.generated.mjs');
writeFileSync(target, out);
console.log(`wrote ${target}`);
console.log(`  SOLUTIONS  ${solutions.length} bytes`);
console.log(`  STAGES     ${stages.length} bytes`);
console.log(`  PRIORITIES ${priorities.length} bytes`);
console.log(`  seedData   ${seedData.length} bytes`);

// sanity: import it and run seedData()
const mod = await import(pathToFileURL(target).href + '?t=' + Date.now());
const d = mod.seedData();
const counts = Object.fromEntries(
  Object.entries(d).filter(([, v]) => Array.isArray(v)).map(([k, v]) => [k, v.length])
);
console.log('seedData() ->', JSON.stringify(counts));
